#!/usr/bin/env node
// wrangler d1 migrations requires one flat, sequentially-numbered directory, so a
// plugin can't just drop SQL files in its own migrations/ folder and have them
// apply on their own. This copies each plugins/<name>/migrations/*.sql into the
// root migrations/ directory, renumbered into a reserved per-plugin block
// (1000-1099, 1100-1199, ...) assigned by alphabetical plugin order, so plugin
// migrations always sort after the core app's (0001-0999) and never collide with
// each other. Re-run after adding/editing a plugin migration: `yarn plugins:sync`.

import { readdirSync, existsSync, readFileSync, writeFileSync, unlinkSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const pluginsDir = path.join(projectRoot, 'plugins');
const migrationsDir = path.join(projectRoot, 'migrations');

const GENERATED_MARKER = '-- GENERATED by script/plugins/sync-migrations.js';
const BLOCK_START = 1000;
const BLOCK_SIZE = 100;

if (!existsSync(pluginsDir)) {
  console.log('No plugins/ directory found — nothing to sync.');
  process.exit(0);
}

// Clear out previously generated files first, so a removed/renamed plugin
// migration doesn't leave a stale copy behind in migrations/.
for (const file of readdirSync(migrationsDir)) {
  if (!file.endsWith('.sql')) continue;
  const full = path.join(migrationsDir, file);
  if (readFileSync(full, 'utf8').startsWith(GENERATED_MARKER)) {
    unlinkSync(full);
  }
}

const pluginNames = readdirSync(pluginsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

let synced = 0;
pluginNames.forEach((pluginName, pluginIndex) => {
  const pluginMigrationsDir = path.join(pluginsDir, pluginName, 'migrations');
  if (!existsSync(pluginMigrationsDir)) return;

  const files = readdirSync(pluginMigrationsDir)
    .filter((f) => f.endsWith('.sql'))
    .sort();
  if (files.length > BLOCK_SIZE) {
    throw new Error(`Plugin "${pluginName}" has more than ${BLOCK_SIZE} migrations — raise BLOCK_SIZE.`);
  }

  const blockStart = BLOCK_START + pluginIndex * BLOCK_SIZE;
  files.forEach((file, fileIndex) => {
    const globalNumber = String(blockStart + fileIndex).padStart(4, '0');
    const description = file.replace(/^\d+_/, '').replace(/\.sql$/, '');
    const outName = `${globalNumber}_${pluginName}__${description}.sql`;
    const source = readFileSync(path.join(pluginMigrationsDir, file), 'utf8');
    writeFileSync(
      path.join(migrationsDir, outName),
      `${GENERATED_MARKER} — source: plugins/${pluginName}/migrations/${file}\n\n${source}`,
    );
    synced++;
  });
});

console.log(`Synced ${synced} plugin migration(s) into migrations/.`);
